"""
Работа с per-stand лог-файлом: tail последних N строк и генератор "follow"
(аналог ``tail -f``) для стрим-панели GUI/агента.

Читает файл как текст в UTF-8 с заменой нечитаемых байт (``errors="replace"``),
чтобы не падать на бинарном мусоре или другой кодировке, изредка попадающей в
лог дочернего .NET-процесса.
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Iterator


def tail(log_path: Path, n: int = 100) -> list[str]:
    """
    Возвращает последние ``n`` строк файла лога (без завершающих переводов строк).

    Если файла ещё нет (стенд ни разу не запускался) — возвращает пустой список,
    а не бросает исключение: отсутствие лога — обычное состояние свежей записи
    реестра.

    Реализация читает файл целиком построчно — для типичных per-stand логов
    (десятки МБ) этого достаточно; TODO(следующая итерация): постраничное
    чтение с конца файла для очень больших логов (сотни МБ и больше), чтобы не
    держать в памяти файл целиком.
    """
    p = Path(log_path)
    if not p.exists():
        return []
    with p.open("r", encoding="utf-8", errors="replace") as f:
        lines = f.readlines()
    tail_lines = lines[-n:] if n > 0 else []
    return [line.rstrip("\n").rstrip("\r") for line in tail_lines]


def follow(log_path: Path, *, poll_interval: float = 0.5) -> Iterator[str]:
    """
    Генератор, отдающий новые строки лога по мере их появления (аналог ``tail -f``).

    Блокирующий: между появлениями новых строк "спит" ``poll_interval`` секунд.
    Предназначен для использования в отдельном потоке/соединении (например,
    long-poll или SSE-эндпоинт агента) — вызывающая сторона сама решает, когда
    остановить итерацию (просто перестать тянуть значения из генератора).

    TODO(следующая итерация): обработка ротации лог-файла (например, через
    logrotate) — сейчас при пересоздании файла с тем же именем позиция чтения
    может "уехать" за пределы нового файла и follow() перестанет отдавать строки
    до следующего перезапуска процесса-читателя.
    """
    p = Path(log_path)
    # Ждём появления файла, если стенд ещё не успел его создать.
    while not p.exists():
        time.sleep(poll_interval)

    with p.open("r", encoding="utf-8", errors="replace") as f:
        f.seek(0, 2)  # сразу к концу файла — follow не показывает историю
        while True:
            line = f.readline()
            if line:
                yield line.rstrip("\n").rstrip("\r")
            else:
                time.sleep(poll_interval)
