"""Общие настройки прогона тестов репозитория.

Две задачи: взвести барьеры состояния машины (GAP-414, их код — `tests/conftest.py`)
ДО первого импорта пакетов и выключить ФОНОВЫЙ планировщик канала обновлений
(`standkit_companion`) на время тестов.

Зачем. Секция `companion` конфига хаба включена по умолчанию (цикл паттернов), а хаб
поднимает планировщик в конструкторе `HubHTTPServer`. Значит на машине, где рядом стоит
платная редакция с ЖИВОЙ лицензией, каждый тест, поднимающий хаб (`tests/test_hub_*.py` —
их больше сотни), заводил бы настоящий фоновый поток. Первый тик разбрасывается по минуте,
поэтому обычно он не успевает сработать за прогон, — но «обычно» здесь означает
недетерминированный тест, который при неудачном жребии запускает CLI BPMkit и уходит в
сеть к бэкенду издателя посреди `pytest`.

Лечить это правкой конфига в каждом тестовом помощнике — договорённость, которую забудут
при следующем новом файле тестов. Одна переменная окружения выключает канал для всего
прогона в одном месте; тесты самого канала выставляют её обратно точечно.

`setdefault`, а не присваивание: если разработчик сознательно поднял переменную сам
(например, гоняет ручной сценарий с включённым каналом), мы его решение не перебиваем.
"""
