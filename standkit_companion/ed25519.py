# -*- coding: utf-8 -*-
"""Проверка подписи Ed25519 (RFC 8032, PureEdDSA) — чистый Python, только stdlib.

Зачем своя реализация. Канал обновлений проверяет подпись ИСПОЛНЯЕМОГО кода, и это
единственное, что отделяет пользователя от установки чужого бинаря. Взять `cryptography`
или `pynacl` нельзя: весь репозиторий stdlib-only (см. докстринг пакета), а тянуть
compiled-зависимость ради одной проверки в релиз — менять один риск на другой. Поэтому
здесь ~200 строк арифметики, которые можно перечитать целиком перед каждым релизом.

Что ЗДЕСЬ ЕСТЬ и чего здесь НЕТ:

* есть только `verify`. Подписи не создаются никогда — приватного ключа на клиенте нет и
  быть не может, а наличие в поставке готового `sign` превращает случайную утечку seed'а в
  готовый инструмент подделки. Тестовый `sign` живёт в `tests/`, не в поставке;
* нет ph/ctx-вариантов (Ed25519ph, Ed25519ctx): издатель подписывает PureEdDSA, а мёртвая
  ветка кода в проверяльщике подписи — это место, где прячется ошибка.

О сопротивлении атакам по времени. Его здесь НЕТ и оно не нужно: все входные данные —
ПУБЛИЧНЫЕ (открытый ключ, подпись, сообщение), секрета в этом коде не обрабатывается ни
одного. Утечка по времени раскрыла бы ровно то, что и так лежит в открытом файле.

Строгость проверок (каждая ниже прокомментирована по месту, здесь — сводка):

* `S < L` — обязательно. Без этой проверки к валидной подписи можно прибавить L и получить
  вторую, тоже «валидную» подпись того же сообщения (malleability). Для канала обновлений
  это означало бы, что sha256 сайдкара перестаёт однозначно соответствовать подписи;
* точки распаковываются строго: `y >= p`, отсутствующий квадратный корень и `x == 0` при
  запрошенном отрицательном знаке — отказ, а не «как-нибудь досчитаем»;
* `verify` НИКОГДА не бросает исключение: на вход приходит содержимое файла из сети, и
  падение с трейсбеком вместо `False` — это отказ канала по причине «неверный формат»,
  который выглядит как баг.

Проверка равенства `[S]B == R + [k]A` идёт по КАНОНИЧЕСКИМ сжатым представлениям обеих
точек (`_point_compress`), а не по расширенным координатам: одна и та же точка имеет
бесконечно много представлений (X:Y:Z:T), и сравнение полей напрямую дало бы ложный
отказ. Сжатие — это и есть приведение к аффинным координатам.
"""
from __future__ import annotations

import hashlib
from typing import Optional, Tuple

__all__ = ["verify"]

# --------------------------------------------------------------------------------------
# Параметры кривой edwards25519 (RFC 8032 §5.1). Имена — как в RFC, чтобы код можно было
# читать рядом с текстом стандарта.
# --------------------------------------------------------------------------------------

#: Характеристика поля.
P = 2 ** 255 - 19

#: Порядок базовой точки (простой множитель порядка группы). Ровно им ограничен S в подписи.
L = 2 ** 252 + 27742317777372353535851937790883648493

#: Длины сырых представлений (Raw-кодирование, никаких PEM/DER — в проекте везде так).
KEY_SIZE = 32
SIGNATURE_SIZE = 64

# d = -121665/121666 mod p — параметр скрученной кривой Эдвардса (a = -1).
_D = (-121665 * pow(121666, P - 2, P)) % P

# sqrt(-1) mod p — нужен при извлечении квадратного корня: p ≡ 5 (mod 8), поэтому
# кандидат в корни может отличаться от истинного ровно на этот множитель.
_SQRT_M1 = pow(2, (P - 1) // 4, P)

# Точка в расширенных координатах (X : Y : Z : T), где x = X/Z, y = Y/Z, x*y = T/Z.
# Расширенные координаты выбраны потому, что дают формулы сложения БЕЗ ветвлений и без
# деления в поле — деление (pow(..., P-2, P)) стоит дороже всего остального вместе взятого.
Point = Tuple[int, int, int, int]

#: Нейтральный элемент группы (аффинно — точка (0, 1)).
_IDENTITY: Point = (0, 1, 1, 0)


def _recover_x(y: int, sign: int) -> Optional[int]:
    """Восстановить x по y и биту знака. `None`, если такой точки на кривой нет.

    Уравнение кривой даёт x² = (y² − 1)/(d·y² + 1). Корень считается по формуле для
    p ≡ 5 (mod 8) без обращения в поле: x = u·v³·(u·v⁷)^((p−5)/8), где u = y²−1, v = d·y²+1.
    """
    if y >= P:
        # Не-каноническое кодирование y (значение ≥ p). RFC 8032 разрешает отвергать такое,
        # и мы отвергаем: два разных байта, дающих одну точку, — это лишняя степень свободы
        # у того, кто подсовывает нам ключ или подпись.
        return None

    u = (y * y - 1) % P
    v = (_D * y * y + 1) % P
    if v == 0:
        return None

    x = (u * pow(v, 3, P) % P) * pow(u * pow(v, 7, P) % P, (P - 5) // 8, P) % P

    vxx = (v * x * x) % P
    if vxx == u:
        pass
    elif vxx == (-u) % P:
        # Попали в «другой» корень — поправка на sqrt(-1).
        x = (x * _SQRT_M1) % P
    else:
        # Квадратного корня не существует: точка не лежит на кривой.
        return None

    if x == 0 and sign == 1:
        # x = 0 имеет единственное представление, «отрицательного нуля» не бывает.
        # Требование знака 1 при x = 0 — признак не-канонической (подделанной) кодировки.
        return None

    if x % 2 != sign:
        x = P - x
    return x


def _point_decompress(data: bytes) -> Optional[Point]:
    """32 байта сжатой точки → точка в расширенных координатах. `None` при любой порче.

    Формат (RFC 8032 §5.1.2): y в little-endian, старший бит последнего байта — знак x.
    """
    if len(data) != KEY_SIZE:
        return None
    value = int.from_bytes(data, "little")
    sign = (value >> 255) & 1
    y = value & ((1 << 255) - 1)
    x = _recover_x(y, sign)
    if x is None:
        return None
    return (x, y, 1, (x * y) % P)


def _point_compress(point: Point) -> bytes:
    """Точка → 32 байта канонического сжатого представления.

    Здесь и происходит приведение к аффинным координатам: одно обращение Z⁻¹ на точку.
    Именно поэтому сравнивать точки дешевле и надёжнее в сжатом виде, а не покоординатно.
    """
    x, y, z, _t = point
    z_inv = pow(z, P - 2, P)
    x = (x * z_inv) % P
    y = (y * z_inv) % P
    return (y | ((x & 1) << 255)).to_bytes(KEY_SIZE, "little")


def _point_add(a: Point, b: Point) -> Point:
    """Сложение в расширенных координатах (a = −1), формулы «add-2008-hwcd-3».

    Формулы ПОЛНЫЕ для этой кривой: одинаково корректны для сложения разных точек, для
    удвоения и для нейтрального элемента. Отсутствие особых случаев здесь — не экономия
    строк, а отсутствие ветки, которую невозможно покрыть тестом.
    """
    ax, ay, az, at = a
    bx, by, bz, bt = b
    m = (ay - ax) * (by - bx) % P
    n = (ay + ax) * (by + bx) % P
    c = 2 * at * bt * _D % P
    d = 2 * az * bz % P
    e = n - m
    f = d - c
    g = d + c
    h = n + m
    return (e * f % P, g * h % P, f * g % P, e * h % P)


def _point_mul(scalar: int, point: Point) -> Point:
    """Умножение точки на скаляр обычным double-and-add по битам (LSB → MSB).

    Ни оконных методов, ни предвычисленных таблиц: одна проверка на релиз стоит миллисекунды,
    а каждая оптимизация здесь — это ещё десяток строк, которые придётся перечитывать
    при аудите. Скаляр публичный, поэтому зависимость времени от его битов безвредна.
    """
    result = _IDENTITY
    addend = point
    while scalar > 0:
        if scalar & 1:
            result = _point_add(result, addend)
        addend = _point_add(addend, addend)
        scalar >>= 1
    return result


# Базовая точка B: y = 4/5, x — положительный корень (знак 0). Считается через ту же
# распаковку, что и любой ключ: если бы `_recover_x` был сломан, B получился бы неверным
# и НИ ОДИН тест-вектор RFC не сошёлся бы — это дешёвая самопроверка при импорте.
_BASE_Y = 4 * pow(5, P - 2, P) % P
_BASE_X = _recover_x(_BASE_Y, 0)
assert _BASE_X is not None, "не удалось восстановить базовую точку edwards25519"
_BASE: Point = (_BASE_X, _BASE_Y, 1, (_BASE_X * _BASE_Y) % P)


def _scalarmult_base(scalar: int) -> Point:
    """[scalar]B — умножение базовой точки. Вынесено отдельно, потому что это единственная
    операция, которая нужна и проверке, и тестовому генератору подписей."""
    return _point_mul(scalar, _BASE)


def _as_bytes(value: object) -> Optional[bytes]:
    """Привести к `bytes` то, что реально является байтами. Иначе — `None`.

    Явная проверка вместо `try: bytes(value)`: `bytes(5)` вернёт пять нулевых байтов, то
    есть молча превратит мусор в «валидный» вход нужной длины.
    """
    if isinstance(value, (bytes, bytearray, memoryview)):
        return bytes(value)
    return None


def verify(public_key: bytes, signature: bytes, message: bytes) -> bool:
    """Проверить подпись Ed25519. `True` — подпись подтверждена этим ключом для этого
    сообщения; `False` — во всех остальных случаях, включая мусор на входе.

    Исключений не бросает СОЗНАТЕЛЬНО: все три аргумента приходят из сети или с диска, и
    единственный осмысленный ответ на «это не подпись» — «подпись не подтверждена».
    Вызывающий переводит `False` в типизированный отказ канала сам (см. `signature.py`),
    потому что только он знает, что именно проверялось.
    """
    pub = _as_bytes(public_key)
    sig = _as_bytes(signature)
    msg = _as_bytes(message)
    if pub is None or sig is None or msg is None:
        return False
    if len(pub) != KEY_SIZE or len(sig) != SIGNATURE_SIZE:
        return False

    # A — открытый ключ как точка. Не распаковался — ключ не является точкой кривой.
    a_point = _point_decompress(pub)
    if a_point is None:
        return False

    # R — первая половина подписи, тоже точка.
    r_bytes = sig[:KEY_SIZE]
    r_point = _point_decompress(r_bytes)
    if r_point is None:
        return False

    # S — вторая половина, скаляр. ОБЯЗАТЕЛЬНО меньше L: S и S+L дали бы две разные подписи
    # одного и того же сообщения одним ключом (malleability). Для канала обновлений это
    # значит, что «подпись артефакта» перестаёт быть уникальным свидетельством.
    s_value = int.from_bytes(sig[KEY_SIZE:], "little")
    if s_value >= L:
        return False

    # k = SHA-512(R || A || M) mod L — привязка подписи и к ключу, и к сообщению разом.
    digest = hashlib.sha512(r_bytes + pub + msg).digest()
    k = int.from_bytes(digest, "little") % L

    # Уравнение проверки: [S]B == R + [k]A.
    left = _scalarmult_base(s_value)
    right = _point_add(r_point, _point_mul(k, a_point))
    return _point_compress(left) == _point_compress(right)
