# -*- coding: utf-8 -*-
"""BPMkitStand Companion — клиентская половина канала доставки обновлений издателя.

Что это. Служба-компаньон, которую поднимает процесс хаба (`standkit_hub`). Она ходит к
бэкенду издателя BPMkit за двумя РАЗНЫМИ по цене ошибки вещами и потому применяет к ним
разные политики:

* **паттерны** (`/v1/content/patterns/sync`) — markdown, не исполняемый код. Достаточно
  целостности (`sha256`/`bundle_sha256`); подпись тела — опциональное ужесточение, дефолт
  «не требовать» (механизма подписи markdown у издателя ещё нет). Цикл включён по умолчанию;
* **релизы** (`/v1/content/releases/...`) — исполняемый бинарь MCP. Политика **строго
  fail-closed и без флага отключения**: нет сайдкара подписи, `signed: false`, sha256 не
  сошёлся, публичный ключ не найден — обновление НЕ применяется, старая версия не трогается,
  причина уходит в состояние и в UI. Цикл выключен по умолчанию (`releases.enabled=false`)
  и остаётся выключенным, пока издатель не выпустит ключ подписи артефактов и не переедет
  на HTTPS-домен (ADR-0022; блокеры Б1/Б2 dev-контура);
* **отзыв лицензий** (`/v1/content/revocations.json`) — публичный эндпоинт БЕЗ конверта.
  Опрашивается даже когда основной канал ответил `401 revoked`: отозванная лицензия не
  пройдёт аутентификацию и иначе никогда не узнала бы об отзыве. Подпись файла проверяется
  ОБЯЗАТЕЛЬНО (он подписан оффлайн уже сегодня); подделка = снятие отзыва.

Границы модуля (см. `docs/adr/0005-companion-transport-in-mit-core.md`):

* модуль — **транспорт**. Ценность (лицензия, содержимое паттернов, подписанные бинари)
  живёт на стороне издателя; без лицензионного конверта модуль честно бездействует и
  сообщает об этом, а не притворяется работающим;
* **stdlib-only**, как и всё ядро репозитория: HTTP — `urllib.request`, проверка подписи —
  собственная чистая реализация Ed25519 (`standkit_companion.ed25519`), никаких pip-зависимостей;
* внешние консольные утилиты — **только** через `standkit.platform.run_console`
  (GAP-138: прямой `subprocess.run` роняет статический тест `tests/test_no_window.py`);
* модуль **не требует прав администратора** в штатном режиме и не пишет в `Program Files`:
  паттерны едут в пользовательский override-корень `%APPDATA%\\BPMkit\\patterns\\references`,
  бинарь стейджится в пользовательский временный каталог. Служба под LocalSystem, пишущая
  скачанное из сети в системные каталоги, — прямое нарушение `SECURITY.md`.

Лицензионный конверт модуль **не резолвит сам** — это была бы третья копия логики
(`BPMkit/server/bpmkit/licensing.py` + бэкенд + здесь). Вместо этого он спрашивает готовый
контекст у CLI самого MCP: `standkit_companion.context` вызывает `bpmkit setup
companion-context --json` через `run_console` и получает конверт, базовый URL, версию MCP и
пути поставки. Нет MCP рядом — честный отказ «лицензионный контекст недоступен», не тихий
пропуск.

Точка расширения редакции. Ядро `standkit_hub` импортирует этот пакет МЯГКО
(`try/except ImportError`) и, если его нет, отдаёт `/api/companion/*` с `503` и
`edition: "free"`. Ветвления по имени файла/хардкода редакции в ядре нет.
"""
from __future__ import annotations

__all__ = [
    "__version__",
    "COMPANION_API_VERSION",
    "is_available",
    "describe",
]

# Версия самого канала (протокола обмена состоянием с хабом), НЕ версия standkit.
__version__ = "1.0.0"

# Версия контракта /api/companion/* — растёт при несовместимом изменении формы ответов.
COMPANION_API_VERSION = 1


def is_available() -> bool:
    """Пакет импортирован — значит редакция с каналом обновлений установлена.

    Отдельная функция, а не «модуль импортировался», нужна ядру хаба: оно спрашивает именно
    её, чтобы будущая деградация («пакет есть, но окружение не поддерживает канал») могла
    вернуть False, не ломая контракт импорта.
    """
    return True


def describe() -> dict:
    """Короткая карточка модуля для `/api/version` и раздела «О программе»."""
    return {
        "edition": "companion",
        "companion_version": __version__,
        "api_version": COMPANION_API_VERSION,
    }
